import { Injectable } from '@nestjs/common';
import {
  CanonicalContract,
  exportToOpenApiJson,
  exportToOpenApiYaml,
  exportToPostmanJson,
} from '@apiforge/shared';
import { StorageService } from '../storage/storage.service';
import { PdfGeneratorService } from './pdf-generator.service';
import archiver from 'archiver';
import { Writable } from 'stream';

@Injectable()
export class ZipPackagingService {
  constructor(
    private readonly storageService: StorageService,
    private readonly pdfGenerator: PdfGeneratorService,
  ) {}

  /**
   * Bundles OpenAPI JSON, OpenAPI YAML, Postman Collection, and HTML/PDF Documentation into a single ZIP archive.
   */
  async packageCompleteZip(
    contract: CanonicalContract,
  ): Promise<{ token: string; downloadUrl: string; sizeBytes: number }> {
    const safeName = contract.name.toLowerCase().replace(/[^a-z0-9]/g, '-');
    const zipFilename = `${safeName}-v${contract.version}-bundle.zip`;

    const openApiJson = exportToOpenApiJson(contract, true);
    const openApiYaml = exportToOpenApiYaml(contract);
    const postmanJson = exportToPostmanJson(contract, true);
    const docHtml = this.pdfGenerator.generatePrintHtml(contract);

    const readmeMd = `# ${contract.name} (v${contract.version}) - API Package

Generated by **ApiForge** on ${new Date().toUTCString()}

## Package Contents
- \`openapi.json\`: Standard OpenAPI 3.1.0 specification (JSON format).
- \`openapi.yaml\`: Standard OpenAPI 3.1.0 specification (YAML format).
- \`postman_collection.json\`: Postman Collection v2.1.0 ready for import into Postman, Insomnia, or Bruno.
- \`documentation.html\`: Self-contained, print-styled developer reference manual with print stylesheet.

## Endpoints (${contract.endpoints.length})
${contract.endpoints.map((ep) => `- \`${ep.method}\` ${ep.path} - ${ep.summary}`).join('\n')}

---
Exported with zero cloud storage dependency via ApiForge Local Storage Vault.
`;

    // Stream into memory buffer using archiver
    const zipBuffer = await new Promise<Buffer>((resolve, reject) => {
      const chunks: Buffer[] = [];
      const bufferStream = new Writable({
        write(chunk, _encoding, next) {
          chunks.push(Buffer.from(chunk));
          next();
        },
      });

      const archive = archiver('zip', {
        zlib: { level: 9 },
      });

      bufferStream.on('finish', () => resolve(Buffer.concat(chunks)));
      bufferStream.on('error', reject);
      archive.on('error', reject);

      archive.pipe(bufferStream);

      archive.append(openApiJson, { name: 'openapi.json' });
      archive.append(openApiYaml, { name: 'openapi.yaml' });
      archive.append(postmanJson, { name: 'postman_collection.json' });
      archive.append(docHtml, { name: 'documentation.html' });
      archive.append(readmeMd, { name: 'README.md' });

      archive.finalize();
    });

    return this.storageService.saveExportArtifact(
      zipFilename,
      zipBuffer,
      'application/zip',
      24,
    );
  }
}
